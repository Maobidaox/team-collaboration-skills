# 赛道 → 钩子类型偏好
GENRE_PREF = {
    "都市脑洞": ["反转", "悬念", "打脸前置"],
    "动漫衍生": ["揭示", "悬念", "反转"],
    "玄幻": ["危机", "打脸前置", "揭示"],
    "女频·双男主": ["情感", "揭示", "悬念"],
    "女频·快穿": ["反转", "揭示", "危机"],
    "专业流": ["打脸前置", "揭示", "悬念"],
    "科幻末世": ["危机", "悬念", "反转"],
    "悬疑": ["悬念", "揭示", "危机"],
}


def main():
    ap = argparse.ArgumentParser(description="章末钩子与追更锚点生成器")
    ap.add_argument("--type", help="指定钩子类型")
    ap.add_argument("--genre", help="赛道（按赛道偏好生成）")
    ap.add_argument("-n", type=int, default=10, help="生成条数")
    ap.add_argument("--anchor", action="store_true", help="生成追更锚点")
    ap.add_argument("--types", action="store_true", help="查看全部钩子类型")
    ap.add_argument("--seed", type=int, help="随机种子（可复现）")
    args = ap.parse_args()

    if args.seed is not None:
        random.seed(args.seed)
    else:
        random.seed()

    if args.types:
        print("可用钩子类型：")
        for k, v in HOOKS.items():
            print(f"  {k:<10} {len(v)} 条")
        print("\n赛道 → 偏好类型：")
        for g, p in GENRE_PREF.items():
            print(f"  {g:<12} {' / '.join(p)}")
        return 0

    if args.anchor:
        print("=" * 70)
        print("追更锚点（建议每 3-5 章放置 1 个）")
        print("=" * 70)
        picks = random.sample(ANCHORS, min(args.n, len(ANCHORS)))
        for i, (kind, txt) in enumerate(picks, 1):
            print(f"\n{i}. [{kind}]")
            print(f"   {txt}")
        print("\n" + "=" * 70)
        print("用法提示：")
        print("  · {地点} / {X} 等占位符需替换为本书具体内容")
        print("  · 锚点放在章末最后 1-2 句，效果最佳")
        print("  · 蔡格尼克效应：未完成的张力 = 读者明天回来的理由")
        return 0

    types = [args.type] if args.type else (GENRE_PREF.get(args.genre or "", list(HOOKS.keys())))
    types = [t for t in types if t in HOOKS] or list(HOOKS.keys())

    print("=" * 70)
    print(f"章末钩子生成（类型：{' / '.join(types)}）")
    print("=" * 70)
    pool = []
    for t in types:
        pool.extend([(t, h) for h in HOOKS[t]])
    picks = random.sample(pool, min(args.n, len(pool)))
    for i, (t, h) in enumerate(picks, 1):
        print(f"\n{i}. [{t}]")
        print(f"   {h}")
    print("\n" + "=" * 70)
    print("使用纪律：")
    print("  · 章末钩子必须是**未完成的张力**，不是总结")
    print("  · 钩子强度递增：前一章的钩子 < 后一章的钩子")
    print("  · 每 3-5 章配 1 个追更锚点（--anchor）")
    print("  · 钩子要可兑现：下一章开头必须回应，否则读者会失望")
    return 0


if __name__ == "__main__":
    sys.exit(main())
